package com.motion.backend.media;

import com.motion.backend.config.MotionProperties;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;
import org.junit.jupiter.api.Assumptions;

import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.io.InputStream;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.StandardCopyOption;
import java.util.Arrays;

import static org.assertj.core.api.Assertions.assertThat;

/**
 * Cross-implementation checks against the authoritative Go {@code mediacrypt} package.
 *
 * <p>The committed fixture was generated by Go from the source in this repository. The reverse
 * direction runs the Go package as an external process when a Go toolchain is available.</p>
 */
class GoCompatibilityTest {

    private static final String MASTER_KEY = "AAECAwQFBgcICQoLDA0ODxAREhMUFRYXGBkaGxwdHh8=";

    @TempDir
    Path tempDir;

    @Test
    void javaReadsAndSeeksInsideGoGeneratedFixture() throws Exception {
        Path plaintext = resource("fixtures/go-plaintext.bin");
        Path ciphertext = resource("fixtures/go-encrypted.bin");
        String wrappedKey = Files.readString(resource("fixtures/go-wrapped.key")).trim();
        byte[] expected = Files.readAllBytes(plaintext);
        MediaCrypto crypto = crypto();

        assertThat(Files.readAllBytes(ciphertext)).startsWith("MOTIONE1".getBytes(StandardCharsets.US_ASCII));
        try (MediaSource source = crypto.openEncrypted(ciphertext, wrappedKey)) {
            assertThat(source.size()).isEqualTo(expected.length);
            assertThat(readAll(source)).isEqualTo(expected);

            int boundary = MediaCrypto.CHUNK_SIZE;
            assertRange(source, boundary - 10, boundary + 20, expected);
            assertRange(source, expected.length - 111, expected.length - 1, expected);
            source.seek(0);
            byte[] head = new byte[32];
            assertThat(source.read(head, 0, head.length)).isEqualTo(head.length);
            assertThat(head).isEqualTo(Arrays.copyOfRange(expected, 0, head.length));
        }
    }

    @Test
    void goDecryptsJavaGeneratedFixture() throws Exception {
        Assumptions.assumeTrue(goAvailable(), "Go toolchain is not installed");
        Path repository = Path.of(System.getProperty("user.dir")).getParent();
        Assumptions.assumeTrue(repository != null && Files.exists(repository.resolve("go.mod")),
                "Go module root is not available");

        byte[] plaintext = Files.readAllBytes(resource("fixtures/go-plaintext.bin"));
        Path plainPath = tempDir.resolve("java-plain.bin");
        Path cipherPath = tempDir.resolve("java-encrypted.bin");
        Files.write(plainPath, plaintext);

        MediaCrypto crypto = crypto();
        byte[] dek = crypto.newDek();
        crypto.encryptFile(plainPath, cipherPath, dek);
        String wrappedKey = crypto.wrapDek(dek);
        Files.writeString(tempDir.resolve("java-wrapped.key"), wrappedKey);

        Path goDir = Files.createDirectories(tempDir.resolve("go-compat"));
        Files.writeString(goDir.resolve("go.mod"), """
                module github.com/SwayKh/Motion/compat

                go 1.26.2

                require github.com/SwayKh/Motion v0.0.0

                replace github.com/SwayKh/Motion => %s
                """.formatted(repository.toAbsolutePath().normalize()));
        Files.writeString(goDir.resolve("main.go"), goHelper());

        Path decrypted = tempDir.resolve("go-decrypted.bin");
        ProcessBuilder builder = new ProcessBuilder(
                "go", "run", ".", "decrypt", cipherPath.toString(),
                tempDir.resolve("java-wrapped.key").toString(), decrypted.toString());
        builder.directory(goDir.toFile());
        builder.environment().put("GOFLAGS", "-mod=mod");
        Path errorLog = tempDir.resolve("go-decrypt.err");
        builder.redirectError(errorLog.toFile());
        Process process = builder.start();
        int exit = process.waitFor();
        assertThat(exit).as("Go decryption failed: %s", Files.readString(errorLog)).isZero();
        assertThat(Files.readAllBytes(decrypted)).isEqualTo(plaintext);
    }

    private static void assertRange(MediaSource source, long start, long end, byte[] expected) throws IOException {
        source.seek(start);
        byte[] buffer = new byte[(int) (end - start + 1)];
        int total = 0;
        while (total < buffer.length) {
            int read = source.read(buffer, total, buffer.length - total);
            assertThat(read).isPositive();
            total += read;
        }
        assertThat(buffer).isEqualTo(Arrays.copyOfRange(expected, (int) start, (int) end + 1));
    }

    private static byte[] readAll(MediaSource source) throws IOException {
        ByteArrayOutputStream output = new ByteArrayOutputStream();
        MediaCrypto.copy(source, output, null);
        return output.toByteArray();
    }

    private static MediaCrypto crypto() {
        MotionProperties properties = new MotionProperties();
        properties.getEncryption().setKey(MASTER_KEY);
        return new MediaCrypto(properties);
    }

    private Path resource(String name) throws IOException {
        Path target = Files.createTempFile(tempDir, "resource-", ".bin");
        try (InputStream input = getClass().getClassLoader().getResourceAsStream(name)) {
            assertThat(input).as("test resource %s", name).isNotNull();
            Files.copy(input, target, StandardCopyOption.REPLACE_EXISTING);
        }
        return target;
    }

    private static boolean goAvailable() {
        try {
            Process process = new ProcessBuilder("go", "version")
                    .redirectErrorStream(true).start();
            return process.waitFor() == 0;
        } catch (IOException | InterruptedException exception) {
            if (exception instanceof InterruptedException) {
                Thread.currentThread().interrupt();
            }
            return false;
        }
    }

    private static String goHelper() {
        return """
                package main

                import (
                    "bytes"
                    "fmt"
                    "os"

                    "github.com/SwayKh/Motion/internal/mediacrypt"
                )

                const masterKey = "AAECAwQFBgcICQoLDA0ODxAREhMUFRYXGBkaGxwdHh8="

                func main() {
                    km, err := mediacrypt.NewKeyManager(masterKey)
                    if err != nil { panic(err) }
                    ciphertext, err := os.ReadFile(os.Args[2])
                    if err != nil { panic(err) }
                    wrapped, err := os.ReadFile(os.Args[3])
                    if err != nil { panic(err) }
                    dek, err := km.Unwrap(string(wrapped))
                    if err != nil { panic(err) }
                    var plaintext bytes.Buffer
                    if err := mediacrypt.DecryptStream(&plaintext, bytes.NewReader(ciphertext), dek); err != nil { panic(err) }
                    if err := os.WriteFile(os.Args[4], plaintext.Bytes(), 0o600); err != nil { panic(err) }
                    fmt.Println("ok")
                }
                """;
    }
}
